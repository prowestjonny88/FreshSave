import { session, ok, eq, done } from './e2e-lib.mjs'
const b = await session()
await b.login('aisyah@freshsave.my')
console.log('Buyer journey (Aisyah, individual)')
eq(await b.eval('return location.hash'), '#/market', 'individual lands on Find food')
ok(/needs you today/i.test(await b.text('.strip-act')), 'slim action strip on marketplace home shows the most urgent task')
ok(!(await b.text('body')).includes('Jaya Grocer'), 'no real chain names visible')
const nav = await b.text('#nav'); ok(/Today[\s\S]*TRACK[\s\S]*My food[\s\S]*RESCUE[\s\S]*Find food[\s\S]*Reservations/i.test(nav), 'nav is grouped Today / Track / Rescue')
ok(!(await b.has('#cats [data-id=meat]')) && !(await b.has('#cats [data-id=dairy]')), 'category bar only offers pilot categories')

// search suggestion respects the distance filter
await b.act('setdist', '[data-v="2"]').catch(() => {})
await b.type('#hdr-dist', '2')
await b.type('#q', 'cooking oil')
const sug = await b.text('#sdrop'); ok(!sug.includes('Seri Murni'), 'search suggestions hide listings outside the ~2 km filter')
await b.type('#hdr-dist', 'all')
await b.type('#q', 'cooking oil')
ok((await b.text('#sdrop')).includes('Seri Murni'), 'and shows them again with "Show all"')
await b.type('#q', '')

// product page
await b.hash('#/item/l2'); const item = await b.text('#main')
ok(item.includes('Best before') && item.includes('Collect by'), 'product page shows date type and collect-by')
ok(item.includes('Not verified') && item.includes('does not inspect'), 'product page states seller declarations are unverified')
ok(item.includes('Illustrative photo'), 'generic photos are labelled illustrative')
ok(/Message \(simulated\)/.test(item), 'contact is labelled simulated')
// quantity bounds
for (let i = 0; i < 30; i++) await b.act('qty', '[data-d="1"]')
eq(await b.text('#qtyv'), '18', 'quantity stepper stops at availability')
for (let i = 0; i < 30; i++) await b.act('qty', '[data-d="-1"]')
eq(await b.text('#qtyv'), '1', 'quantity stepper stops at 1')
await b.act('qty', '[data-d="1"]')
await b.act('reserve'); const dlg = await b.modal()
ok(dlg.includes('Total') && dlg.includes('4-digit pickup code') && dlg.includes('locked'), 'reserve dialog explains response window, code and locked terms')
await b.act('mok'); await b.sleep(400)
const h = await b.eval('return location.hash'); ok(/^#\/reservation\/r/.test(h), 'reservation created and opened: ' + h)
let page = await b.text('#main'); ok(page.includes('Waiting for the seller') && page.includes('Respond by'), 'new reservation is pending with a respond-by time')
ok(!/Your pickup code/.test(page) || page.includes('appears here once the seller accepts'), 'pickup code withheld until accepted')
let st = await b.state(); const rid = h.split('/').pop(); let r = st.reservations.find((x) => x.id === rid)
eq(r.qty, 2, 'reserved quantity stored'); eq(r.terms.price, 1.8, 'price snapshotted'); ok(r.respondBy - r.createdAt <= 2 * 36e5 + 5, 'respond-by within policy')
eq(st.listings.find((l) => l.id === 'l2').total, 20, 'listing total (ledger) unchanged by a reservation')
await b.sleep(4600)
page = await b.text('#main'); ok(page.includes('Ready for pickup') && /\b\d{4}\b/.test(page), 'sample seller auto-accepts; buyer sees code')
st = await b.state(); r = st.reservations.find((x) => x.id === rid); ok(!!r.collectBy && r.collectBy <= r.confirmedAt + 24 * 36e5, 'hold period set and capped at 24h')
ok(await b.has('[data-act=rsimulate]') && !(await b.has('[data-act=rcollect]')), 'buyer has NO "confirm collection" control; only a labelled simulation')
ok(page.includes('At pickup, check the food yourself'), 'buyer safety checklist shown')
// cancel path releases units
await b.hash('#/item/l2'); await b.act('reserve'); await b.act('mok'); await b.sleep(400)
const rid2 = (await b.eval('return location.hash')).split('/').pop()
await b.act('rcancel'); await b.act('mok'); await b.sleep(300)
st = await b.state(); eq(st.reservations.find((x) => x.id === rid2).status, 'cancelled', 'buyer cancel works')
// simulated handover
await b.hash('#/reservation/' + rid); await b.act('rsimulate'); await b.act('mok'); await b.sleep(300)
page = await b.text('#main'); ok(page.includes('Simulated handover recorded'), 'simulated handover is labelled as simulated')
ok(await b.has('[data-act=addfrom]'), '"Add to My food" bridge offered after a handover')
await b.act('addfrom'); let m = await b.modal(); ok(m.includes('Pre-filled from your pickup record'), 'Track form opens pre-filled from Rescue')
await b.eval(`document.querySelector('#f-man').requestSubmit()`); await b.sleep(200)
ok((await b.modal()).includes('Tick the box to confirm'), 'cannot save a date without confirming it against the pack')
await b.check('[data-b="man.ok"]'); await b.eval(`document.querySelector('#f-man').requestSubmit()`); await b.sleep(400)
st = await b.state(); const savedNow = await b.eval('return Date.now()'); ok(st.inventory.some((i) => i.name.includes('Gardenia Original') && i.owner === 'u1' && i.addedAt > savedNow - 20000 && i.qty === 2), 'item added to My food with confirmed date')
await b.hash('#/impact'); page = await b.text('#main')
ok(page.includes('excluded') && /simulated handover/.test(page), 'activity page states what is excluded (sample/simulated)')
ok(!/Food Rescued|landfill|kg of food|tonnes/i.test(page) && page.includes('Not measured') && page.includes('not an estimate of food waste avoided'), 'no unsupported impact claims; limits stated')
await b.hash('#/reservations?tab=unknown')
ok((await b.text('#main')).includes('My reservations') && await b.has('.tabs .on'), 'unknown Reservations tab falls back to a valid view')
console.log('JS errors:', b.errors.length ? b.errors : 'none')
ok(b.errors.length === 0, 'no JavaScript errors during buyer journey')
await b.close(); process.exit(done() ? 1 : 0)
